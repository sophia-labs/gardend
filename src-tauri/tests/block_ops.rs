#[test]
fn edit_block_text_applies_ops_in_descending_offset_order() {
    let (doc, fragment) = new_doc();
    {
        let mut txn = doc.transact_mut();
        insert_blocks_into_fragment(&mut txn, &fragment, &[paragraph("b1", "Hello world")], None)
            .unwrap();
        let (element, _) = find_block_in_fragment(&txn, &fragment, "b1").unwrap();
        // Payload order is low-offset first; application must be high-offset
        // first so earlier edits don't shift later offsets.
        let ops = ops_from(vec![insert_op(0.0, "A"), insert_op(11.0, " tail")]);
        let result = edit_block_text(&mut txn, &element, &ops).expect("edit");
        assert_eq!(result.block_id, "b1");
        assert_eq!(result.length_before, 11);
        assert_eq!(result.length_after, 17);
        assert_eq!(result.applied, 2);
    }
    assert_eq!(block_texts(&doc), vec!["AHello world tail"]);
}

#[test]
fn edit_block_text_delete_and_empty_insert_semantics() {
    let (doc, fragment) = new_doc();
    {
        let mut txn = doc.transact_mut();
        insert_blocks_into_fragment(&mut txn, &fragment, &[paragraph("b1", "Hello world")], None)
            .unwrap();
        let (element, _) = find_block_in_fragment(&txn, &fragment, "b1").unwrap();
        // Delete " world"; over-long ranges clamp; empty insert is skipped
        // but a positive-length delete counts as applied.
        let ops = ops_from(vec![insert_op(3.0, ""), delete_op(5.0, 600.0)]);
        let result = edit_block_text(&mut txn, &element, &ops).expect("edit");
        assert_eq!(result.length_before, 11);
        assert_eq!(result.length_after, 5);
        assert_eq!(result.applied, 1, "empty insert skipped, delete applied");
    }
    assert_eq!(block_texts(&doc), vec!["Hello"]);
}

#[test]
fn edit_block_text_uses_utf16_offsets() {
    let (doc, fragment) = new_doc();
    {
        let mut txn = doc.transact_mut();
        // "a😀b" is 4 UTF-16 units (emoji = surrogate pair) but 6 bytes.
        insert_blocks_into_fragment(&mut txn, &fragment, &[paragraph("b1", "a😀b")], None).unwrap();
        let (element, _) = find_block_in_fragment(&txn, &fragment, "b1").unwrap();
        let result =
            edit_block_text(&mut txn, &element, &ops_from(vec![insert_op(3.0, "X")])).unwrap();
        assert_eq!(result.length_before, 4);
        assert_eq!(result.length_after, 5);
    }
    assert_eq!(block_texts(&doc), vec!["a😀Xb"]);

    let (doc, fragment) = new_doc();
    {
        let mut txn = doc.transact_mut();
        insert_blocks_into_fragment(&mut txn, &fragment, &[paragraph("b1", "a😀b")], None).unwrap();
        let (element, _) = find_block_in_fragment(&txn, &fragment, "b1").unwrap();
        let result =
            edit_block_text(&mut txn, &element, &ops_from(vec![delete_op(1.0, 2.0)])).unwrap();
        assert_eq!(result.length_after, 2);
    }
    assert_eq!(block_texts(&doc), vec!["ab"]);
}

#[test]
fn edit_block_text_inherits_formatting_mid_text() {
    let (doc, fragment) = new_doc();
    {
        let mut txn = doc.transact_mut();
        insert_blocks_into_fragment(
            &mut txn,
            &fragment,
            &[json!({
                "type": "paragraph",
                "attrs": { "data-block-id": "b1" },
                "content": [{ "type": "text", "text": "Bold", "marks": [{ "type": "bold" }] }],
            })],
            None,
        )
        .unwrap();
        let (element, _) = find_block_in_fragment(&txn, &fragment, "b1").unwrap();
        // Default inheritFormat splices into the bold run with bold attrs.
        edit_block_text(&mut txn, &element, &ops_from(vec![insert_op(2.0, "xx")])).unwrap();
    }
    let tiptap = ydoc_to_tiptap_json(&doc);
    let content = tiptap["content"][0]["content"]
        .as_array()
        .expect("inline content");
    assert_eq!(
        content.len(),
        1,
        "inherited format keeps one bold run: {content:?}"
    );
    assert_eq!(content[0]["text"], "Boxxld");
    assert_eq!(content[0]["marks"][0]["type"], "bold");
}

