#[test]
fn text_edit_ops_parser_mirrors_ts_filtering() {
    let ops = text_edit_ops_from_payload(Some(&json!([
        { "type": "insert", "offset": 2, "text": "hi" },
        { "type": "delete", "offset": 0, "length": 3 },
        { "type": "format", "offset": 0 },          // unsupported type → skipped
        { "type": "insert" },                        // missing offset → skipped
        { "type": "delete", "offset": 1 },           // missing length → skipped
        { "type": "insert", "offset": "4", "text": "s", "inherit_format": false },
    ])));
    assert_eq!(ops.len(), 3);
    match &ops[0] {
        BlockTextEditOp::Insert {
            offset,
            text,
            attrs,
            inherit_format,
        } => {
            assert_eq!(*offset, 2.0);
            assert_eq!(text, "hi");
            assert!(attrs.is_none());
            assert!(inherit_format.is_none());
        }
        other => panic!("expected insert, got {other:?}"),
    }
    match &ops[1] {
        BlockTextEditOp::Delete { offset, length } => {
            assert_eq!(*offset, 0.0);
            assert_eq!(*length, 3.0);
        }
        other => panic!("expected delete, got {other:?}"),
    }
    match &ops[2] {
        BlockTextEditOp::Insert {
            offset,
            inherit_format,
            ..
        } => {
            assert_eq!(*offset, 4.0, "string offsets coerce via Number()");
            assert_eq!(
                *inherit_format,
                Some(false),
                "snake_case inherit_format honored"
            );
        }
        other => panic!("expected insert, got {other:?}"),
    }

    assert!(text_edit_ops_from_payload(Some(&json!("not an array"))).is_empty());
    assert!(text_edit_ops_from_payload(None).is_empty());
}

#[test]
fn text_edit_ops_parser_preserves_attrs_presence() {
    let ops = text_edit_ops_from_payload(Some(&json!([
        { "type": "insert", "offset": 0, "text": "a", "attrs": { "bold": {} } },
        { "type": "insert", "offset": 0, "text": "b", "attrs": null },
    ])));
    match &ops[0] {
        BlockTextEditOp::Insert {
            attrs: Some(map), ..
        } => assert!(map.contains_key("bold")),
        other => panic!("expected insert with attrs, got {other:?}"),
    }
    match &ops[1] {
        // Explicit null attrs → present-but-empty (suppresses inheritance
        // resolution through toFormatAttrs, exactly like the TS handler).
        BlockTextEditOp::Insert {
            attrs: Some(map), ..
        } => assert!(map.is_empty()),
        other => panic!("expected insert with empty attrs, got {other:?}"),
    }
}

