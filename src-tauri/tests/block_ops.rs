//! Focused tests for the pure core of src/crdt_engine/block_ops.rs:
//! position resolution, ledger hash determinism (against reference vectors
//! generated with the TS canonicalPayloadHash algorithm), the in-Doc
//! operation ledger, and text-edit application against an in-memory Doc
//! built with the module's own insert code.
//!
//! These tests exercise Garden's real library implementation through its
//! deliberately narrow, doc-hidden parity-test surface.

use garden_lib::crdt_engine::block_ops::{
    block_edits_from_payload, block_ids_in_fragment, canonical_payload_hash, clamp_index,
    collect_block_ids, edit_block_text, find_block_in_fragment, insert_blocks_into_fragment,
    prune_ledger, read_block_id_from_json, read_ledger_entry, resolve_insert_index,
    text_edit_ops_from_payload, update_block_attributes, write_ledger_entry, BlockTextEditOp,
    LedgerWriteFields,
};
use garden_lib::crdt_engine::projection::ydoc_to_tiptap_json;
use serde_json::{json, Map, Value};
use yrs::types::xml::XmlFragment;
use yrs::{Doc, Transact, XmlFragmentRef};

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

fn paragraph(block_id: &str, text: &str) -> Value {
    json!({
        "type": "paragraph",
        "attrs": { "data-block-id": block_id },
        "content": [{ "type": "text", "text": text }],
    })
}

fn new_doc() -> (Doc, XmlFragmentRef) {
    let doc = Doc::new();
    let fragment = doc.get_or_insert_xml_fragment("content");
    (doc, fragment)
}

/// Plain text of each top-level block, read from the projected TipTap JSON.
fn block_texts(doc: &Doc) -> Vec<String> {
    let tiptap = ydoc_to_tiptap_json(doc);
    tiptap
        .get("content")
        .and_then(Value::as_array)
        .map(|blocks| blocks.iter().map(inline_text).collect())
        .unwrap_or_default()
}

fn inline_text(node: &Value) -> String {
    if node.get("type").and_then(Value::as_str) == Some("text") {
        return node
            .get("text")
            .and_then(Value::as_str)
            .unwrap_or("")
            .to_string();
    }
    node.get("content")
        .and_then(Value::as_array)
        .map(|children| children.iter().map(inline_text).collect())
        .unwrap_or_default()
}

fn insert_op(offset: f64, text: &str) -> Value {
    json!({ "type": "insert", "offset": offset, "text": text })
}

fn delete_op(offset: f64, length: f64) -> Value {
    json!({ "type": "delete", "offset": offset, "length": length })
}

fn ops_from(values: Vec<Value>) -> Vec<BlockTextEditOp> {
    text_edit_ops_from_payload(Some(&Value::Array(values)))
}

