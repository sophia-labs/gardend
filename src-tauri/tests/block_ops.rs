#[test]
fn update_block_attributes_sets_removes_and_skips_equal_primitives() {
    let (doc, fragment) = new_doc();
    let mut txn = doc.transact_mut();
    insert_blocks_into_fragment(
        &mut txn,
        &fragment,
        &[json!({
            "type": "listItem",
            "attrs": { "data-block-id": "b1", "listType": "bullet", "checked": false },
        })],
        None,
    )
    .unwrap();
    let (element, _) = find_block_in_fragment(&txn, &fragment, "b1").unwrap();

    let mut attrs = Map::new();
    attrs.insert("listType".to_string(), json!("bullet")); // unchanged primitive
    attrs.insert("checked".to_string(), json!(true)); // changed
    attrs.insert("indent".to_string(), json!(2)); // new
    attrs.insert("language".to_string(), Value::Null); // absent → no-op
    let changed = update_block_attributes(&mut txn, &element, &attrs);
    assert_eq!(changed, vec!["checked", "indent"]);

    // null removes an existing attribute.
    let mut attrs = Map::new();
    attrs.insert("checked".to_string(), Value::Null);
    let changed = update_block_attributes(&mut txn, &element, &attrs);
    assert_eq!(changed, vec!["checked"]);
    drop(txn);

    let tiptap = ydoc_to_tiptap_json(&doc);
    let block_attrs = &tiptap["content"][0]["attrs"];
    assert_eq!(block_attrs["indent"], json!(2.0));
    assert!(block_attrs.get("checked").is_none());
}

