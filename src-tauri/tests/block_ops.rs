#[test]
fn ledger_roundtrips_result_envelope_and_hash() {
    let doc = Doc::new();
    let mut txn = doc.transact_mut();

    assert!(read_ledger_entry(&txn, "op-1").is_none());

    let envelope = json!({
        "block_ids": ["b1"],
        "blocks_inserted": 1,
        "blocks_existing": 0,
        "existing_block_ids": [],
        "block_count": 1,
    });
    write_ledger_entry(
        &mut txn,
        "op-1",
        LedgerWriteFields {
            op: "block.insert",
            completed_at: "1760000000000",
            payload_hash: Some("deadbeef".to_string()),
            result: Some(&envelope),
        },
    );

    let hit = read_ledger_entry(&txn, "op-1").expect("replay hit");
    assert_eq!(hit.result, Some(envelope));
    assert_eq!(hit.payload_hash.as_deref(), Some("deadbeef"));
    assert_eq!(hit.completed_at, "1760000000000");
    assert!(read_ledger_entry(&txn, "op-2").is_none());
}

#[test]
fn ledger_drops_oversized_results_but_still_records_application() {
    let doc = Doc::new();
    let mut txn = doc.transact_mut();
    let oversized = json!({ "data": "x".repeat(5000) });
    write_ledger_entry(
        &mut txn,
        "op-big",
        LedgerWriteFields {
            op: "block.editText",
            completed_at: "1760000000000",
            payload_hash: None,
            result: Some(&oversized),
        },
    );
    let hit = read_ledger_entry(&txn, "op-big").expect("applied");
    assert_eq!(
        hit.result, None,
        "results over 4096 UTF-16 units are not cached"
    );
    assert_eq!(hit.payload_hash, None);
}

#[test]
fn prune_ledger_drops_aged_entries_and_caps_count() {
    let doc = Doc::new();
    let mut txn = doc.transact_mut();
    let now: f64 = 1_760_000_000_000.0;

    write_ledger_entry(
        &mut txn,
        "op-ancient",
        LedgerWriteFields {
            op: "block.insert",
            completed_at: "1000", // epoch-millis far past the 7-day window
            payload_hash: None,
            result: None,
        },
    );
    // 1030 fresh entries with strictly increasing timestamps.
    for i in 0..1030 {
        write_ledger_entry(
            &mut txn,
            &format!("op-{i}"),
            LedgerWriteFields {
                op: "block.editText",
                completed_at: &format!("{}", now as i64 - 1030 + i),
                payload_hash: None,
                result: None,
            },
        );
    }

    let removed = prune_ledger(&mut txn, now);
    // 1 aged out + 6 over the 1024 cap (oldest first).
    assert_eq!(removed, 7);
    assert!(read_ledger_entry(&txn, "op-ancient").is_none());
    for i in 0..6 {
        assert!(
            read_ledger_entry(&txn, &format!("op-{i}")).is_none(),
            "op-{i} should be capped out"
        );
    }
    assert!(read_ledger_entry(&txn, "op-6").is_some());
    assert!(read_ledger_entry(&txn, "op-1029").is_some());
}

