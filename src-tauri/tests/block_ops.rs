#[test]
fn resolve_insert_index_matches_ts_semantics() {
    // Default: append at end.
    assert_eq!(resolve_insert_index(None, false, None, 5), 5.0);
    // Reference block: before/after.
    assert_eq!(resolve_insert_index(Some(2), true, None, 5), 2.0);
    assert_eq!(resolve_insert_index(Some(2), false, None, 5), 3.0);
    // Reference block wins over an index hint.
    assert_eq!(resolve_insert_index(Some(1), false, Some(4.0), 5), 2.0);
    // Positive hint clamps to blockCount.
    assert_eq!(resolve_insert_index(None, false, Some(3.0), 5), 3.0);
    assert_eq!(resolve_insert_index(None, false, Some(99.0), 5), 5.0);
    // Negative hint: max(0, blockCount + 1 + hint).
    assert_eq!(resolve_insert_index(None, false, Some(-1.0), 5), 5.0);
    assert_eq!(resolve_insert_index(None, false, Some(-3.0), 5), 3.0);
    assert_eq!(resolve_insert_index(None, false, Some(-99.0), 5), 0.0);
}

#[test]
fn clamp_index_floors_and_bounds() {
    assert_eq!(clamp_index(2.7, 5), 2);
    assert_eq!(clamp_index(-3.0, 5), 0);
    assert_eq!(clamp_index(7.0, 5), 5);
    assert_eq!(clamp_index(f64::NAN, 5), 5);
    assert_eq!(clamp_index(f64::INFINITY, 5), 5);
}

