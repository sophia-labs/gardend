#[test]
fn insert_blocks_appends_and_inserts_at_position() {
    let (doc, fragment) = new_doc();
    {
        let mut txn = doc.transact_mut();
        let ids = insert_blocks_into_fragment(
            &mut txn,
            &fragment,
            &[paragraph("b1", "Hello world"), paragraph("b2", "Second")],
            None,
        )
        .expect("append");
        assert_eq!(ids, vec!["b1", "b2"]);

        // Insert before everything (position 0).
        let ids = insert_blocks_into_fragment(
            &mut txn,
            &fragment,
            &[paragraph("b0", "First")],
            Some(0.0),
        )
        .expect("prepend");
        assert_eq!(ids, vec!["b0"]);

        assert_eq!(
            block_ids_in_fragment(&txn, &fragment),
            vec!["b0", "b1", "b2"]
        );
        let (_, index) = find_block_in_fragment(&txn, &fragment, "b2").expect("find b2");
        assert_eq!(index, 2);
        assert!(find_block_in_fragment(&txn, &fragment, "nope").is_none());
    }
    assert_eq!(block_texts(&doc), vec!["First", "Hello world", "Second"]);
}

#[test]
fn insert_blocks_validates_before_mutating() {
    let (doc, fragment) = new_doc();
    let mut txn = doc.transact_mut();

    let error = insert_blocks_into_fragment(
        &mut txn,
        &fragment,
        &[paragraph("ok", "fine"), json!({ "type": "paragraph" })],
        None,
    )
    .expect_err("missing id must fail");
    assert!(error.contains("data-block-id"), "got: {error}");
    assert_eq!(fragment.len(&txn), 0, "failed insert must not mutate");

    let error = insert_blocks_into_fragment(
        &mut txn,
        &fragment,
        &[json!({ "type": "text", "text": "loose", "attrs": { "data-block-id": "t1" } })],
        None,
    )
    .expect_err("top-level text must fail");
    assert!(error.contains("text node"), "got: {error}");
    assert_eq!(fragment.len(&txn), 0);
}

#[test]
fn read_block_id_from_json_mirrors_ts_fallbacks() {
    assert_eq!(
        read_block_id_from_json(&json!({ "attrs": { "data-block-id": "a" } })).as_deref(),
        Some("a")
    );
    // blockId fallback, including when data-block-id is explicitly null.
    assert_eq!(
        read_block_id_from_json(&json!({ "attrs": { "blockId": "b" } })).as_deref(),
        Some("b")
    );
    assert_eq!(
        read_block_id_from_json(&json!({ "attrs": { "data-block-id": null, "blockId": "c" } }))
            .as_deref(),
        Some("c")
    );
    // Non-string and empty ids do not count.
    assert_eq!(
        read_block_id_from_json(&json!({ "attrs": { "data-block-id": 5 } })),
        None
    );
    assert_eq!(
        read_block_id_from_json(&json!({ "attrs": { "data-block-id": "" } })),
        None
    );
    assert_eq!(read_block_id_from_json(&json!({})), None);
}

