// Canonical payload hash (reference vectors generated by running the exact
// TS canonicalize + fnv1a32 implementation under node)
// ---------------------------------------------------------------------------

#[test]
fn canonical_payload_hash_matches_ts_reference_vectors() {
    assert_eq!(canonical_payload_hash(&json!({})), "5465b825");
    assert_eq!(
        canonical_payload_hash(&json!({
            "blockId": "b1",
            "operations": [{ "type": "insert", "offset": 0, "text": "héllo 😀" }],
        })),
        "318b38ba",
        "UTF-16 code-unit hashing (surrogate pairs) must match charCodeAt"
    );
    assert_eq!(
        canonical_payload_hash(&json!({
            "a": 1,
            "b": [true, null, "x"],
            "c": { "z": 2.5, "y": "q\nr" },
        })),
        "21942f08",
        "sorted keys, escapes, and float formatting must match JSON.stringify"
    );
}

#[test]
fn canonical_payload_hash_is_deterministic_and_payload_sensitive() {
    let payload = json!({ "blockId": "b1", "index": 2 });
    assert_eq!(
        canonical_payload_hash(&payload),
        canonical_payload_hash(&payload.clone())
    );
    assert_ne!(
        canonical_payload_hash(&payload),
        canonical_payload_hash(&json!({ "blockId": "b1", "index": 3 }))
    );
}

