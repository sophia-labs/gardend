/// Port of the TS html write path: prepareHtmlForTipTapImport +
/// generateJSON(html, EXPORT_EXTENSIONS). Returns raw (un-normalized) TipTap
/// JSON: `{type: "doc", content: [...]}`. Feed the result through
/// `normalize_imported_tiptap_json` like the TS pipeline does.
pub(crate) fn html_to_tiptap_json(html: &str) -> Result<Value, String> {
    let mut body = build_body_dom(html);
    flatten_html_lists(&mut body);
    normalize_lists_recursive(&mut body);
    let mut parser = Parser::new();
    parser.add_all(&body, &[]);
    Ok(parser.finish())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn empty_html_yields_filled_doc() {
        let doc = html_to_tiptap_json("").unwrap();
        assert_eq!(doc["type"], "doc");
        let content = doc["content"].as_array().unwrap();
        assert_eq!(content.len(), 1);
        assert_eq!(content[0]["type"], "paragraph");
    }

    #[test]
    fn basic_paragraph_with_marks() {
        let doc = html_to_tiptap_json("<p>a <strong>b</strong></p>").unwrap();
        let para = &doc["content"][0];
        assert_eq!(para["type"], "paragraph");
        assert_eq!(para["content"][0]["text"], "a ");
        assert_eq!(para["content"][1]["marks"][0]["type"], "bold");
    }

    #[test]
    fn nested_list_flattens() {
        let doc = html_to_tiptap_json("<ul><li>a<ul><li>b</li></ul></li></ul>").unwrap();
        let content = doc["content"].as_array().unwrap();
        assert_eq!(content.len(), 2);
        assert_eq!(content[0]["attrs"]["indent"], 0);
        assert_eq!(content[1]["attrs"]["indent"], 1);
        assert_eq!(content[1]["attrs"]["listType"], "bullet");
    }

    #[test]
    fn mark_order_follows_schema_rank() {
        // <em><strong>… nests italic outside bold; output is rank-sorted.
        let doc = html_to_tiptap_json("<p><em><strong>x</strong></em></p>").unwrap();
        let marks = doc["content"][0]["content"][0]["marks"].as_array().unwrap();
        assert_eq!(marks[0]["type"], "bold");
        assert_eq!(marks[1]["type"], "italic");
    }
}
