fn match_tag(el: &DomElement, parent: Option<&DomElement>) -> RuleOut {
    let tag = el.tag.as_str();
    match tag {
        "a" => {
            if let Some(href) = el.attr("href") {
                if !href.is_empty() && is_allowed_uri(href) {
                    let mut attrs = Map::new();
                    attrs.insert("href".to_string(), json!(href));
                    attrs.insert(
                        "target".to_string(),
                        json!(el.attr("target").unwrap_or("_blank")),
                    );
                    attrs.insert(
                        "rel".to_string(),
                        json!(el.attr("rel").unwrap_or("noopener noreferrer nofollow")),
                    );
                    attrs.insert(
                        "class".to_string(),
                        json!(el.attr("class").unwrap_or("editor-link")),
                    );
                    return RuleOut::Mark(MarkInst {
                        rank: RANK_LINK,
                        name: "link",
                        attrs,
                    });
                }
            }
            RuleOut::NoRule
        }
        "span" => {
            // TextStyle: span with a style attribute (consuming: false; the
            // remaining span rules are the unsupported comment/footnote/math
            // ones, so the element is otherwise transparent).
            if el.attr("style").is_some() {
                let mut attrs = Map::new();
                attrs.insert(
                    "fontFamily".to_string(),
                    json!(el.style_prop("font-family").unwrap_or_default()),
                );
                attrs.insert(
                    "fontSize".to_string(),
                    json!(el.style_prop("font-size").unwrap_or_default()),
                );
                return RuleOut::Mark(MarkInst {
                    rank: RANK_TEXT_STYLE,
                    name: "textStyle",
                    attrs,
                });
            }
            RuleOut::NoRule
        }
        "strong" => RuleOut::Mark(MarkInst::simple(RANK_BOLD, "bold")),
        "b" => {
            // getAttrs: node.style.fontWeight !== 'normal'
            if el.style_prop("font-weight").as_deref() == Some("normal") {
                RuleOut::NoRule
            } else {
                RuleOut::Mark(MarkInst::simple(RANK_BOLD, "bold"))
            }
        }
        "code" => RuleOut::Mark(MarkInst::simple(RANK_CODE, "code")),
        "em" => RuleOut::Mark(MarkInst::simple(RANK_ITALIC, "italic")),
        "i" => {
            if el.style_prop("font-style").as_deref() == Some("normal") {
                RuleOut::NoRule
            } else {
                RuleOut::Mark(MarkInst::simple(RANK_ITALIC, "italic"))
            }
        }
        "s" | "del" | "strike" => RuleOut::Mark(MarkInst::simple(RANK_STRIKE, "strike")),
        "u" => RuleOut::Mark(MarkInst::simple(RANK_UNDERLINE, "underline")),
        "mark" => RuleOut::Mark(MarkInst::simple(RANK_HIGHLIGHT, "highlight")),
        "p" => RuleOut::Node {
            nt: Nt::Paragraph,
            attrs: node_attrs(Nt::Paragraph, Some(el), parent, None),
            preserve_full: false,
        },
        "blockquote" => RuleOut::Node {
            nt: Nt::Blockquote,
            attrs: node_attrs(Nt::Blockquote, Some(el), parent, None),
            preserve_full: false,
        },
        "br" => RuleOut::Node {
            nt: Nt::HardBreak,
            attrs: Map::new(),
            preserve_full: false,
        },
        "h1" | "h2" | "h3" => {
            let level = tag[1..].parse::<i64>().unwrap_or(1);
            RuleOut::Node {
                nt: Nt::Heading,
                attrs: node_attrs(Nt::Heading, Some(el), parent, Some(level)),
                preserve_full: false,
            }
        }
        "hr" => RuleOut::Node {
            nt: Nt::HorizontalRule,
            attrs: node_attrs(Nt::HorizontalRule, Some(el), parent, None),
            preserve_full: false,
        },
        "pre" => RuleOut::Node {
            nt: Nt::CodeBlock,
            attrs: node_attrs(Nt::CodeBlock, Some(el), parent, None),
            preserve_full: true,
        },
        "table" => RuleOut::Node {
            nt: Nt::Table,
            attrs: node_attrs(Nt::Table, Some(el), parent, None),
            preserve_full: false,
        },
        "tr" => RuleOut::Node {
            nt: Nt::TableRow,
            attrs: node_attrs(Nt::TableRow, Some(el), parent, None),
            preserve_full: false,
        },
        "th" => RuleOut::Node {
            nt: Nt::TableHeader,
            attrs: node_attrs(Nt::TableHeader, Some(el), parent, None),
            preserve_full: false,
        },
        "td" => RuleOut::Node {
            nt: Nt::TableCell,
            attrs: node_attrs(Nt::TableCell, Some(el), parent, None),
            preserve_full: false,
        },
        "li" => RuleOut::Node {
            nt: Nt::ListItem,
            attrs: node_attrs(Nt::ListItem, Some(el), parent, None),
            preserve_full: false,
        },
        "img" => {
            if el.attr("src").is_some() {
                RuleOut::Node {
                    nt: Nt::Image,
                    attrs: node_attrs(Nt::Image, Some(el), parent, None),
                    preserve_full: false,
                }
            } else {
                RuleOut::NoRule
            }
        }
        "image" => {
            if el.attr("src").is_some() {
                RuleOut::Node {
                    nt: Nt::Image,
                    attrs: node_attrs(Nt::Image, Some(el), parent, None),
                    preserve_full: false,
                }
            } else {
                RuleOut::NoRule
            }
        }
        "div" if el.has_class("image-block") => RuleOut::Node {
            nt: Nt::Image,
            attrs: node_attrs(Nt::Image, Some(el), parent, None),
            preserve_full: false,
        },
        _ if IGNORE_TAGS.contains(&tag) => RuleOut::Ignore,
        _ => RuleOut::NoRule,
    }
}

static BOLD_WEIGHT_RE: LazyLock<regex::Regex> =
    LazyLock::new(|| regex::Regex::new(r"^(bold(er)?|[5-9]\d{2,})$").expect("valid regex"));

/// Port of ParseContext.readStyles over the compiled style-rule list:
/// font-weight=400 (clear bold), font-weight bold-ish (add bold),
/// font-style=normal (clear italic), font-style=italic (add italic),
/// text-decoration line-through (strike), text-decoration underline.
fn read_styles(el: &DomElement, marks: &[MarkInst]) -> Vec<MarkInst> {
    let mut out = marks.to_vec();
    if let Some(value) = el.style_prop("font-weight") {
        if value == "400" {
            out.retain(|m| m.name != "bold");
        } else if BOLD_WEIGHT_RE.is_match(&value) {
            out.push(MarkInst::simple(RANK_BOLD, "bold"));
        }
    }
    if let Some(value) = el.style_prop("font-style") {
        if value == "normal" {
            out.retain(|m| m.name != "italic");
        } else if value == "italic" {
            out.push(MarkInst::simple(RANK_ITALIC, "italic"));
        }
    }
    if let Some(value) = el.style_prop("text-decoration") {
        if value.contains("line-through") {
            out.push(MarkInst::simple(RANK_STRIKE, "strike"));
        }
        if value.contains("underline") {
            out.push(MarkInst::simple(RANK_UNDERLINE, "underline"));
        }
    }
    out
}

