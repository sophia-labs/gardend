//! HTML → garden-schema TipTap JSON, port of the frontend's html write path:
//! frontend/src/native/artifact-ingest.ts parseTipTapWriteContent (html branch)
//! = prepareHtmlForTipTapImport (script/style/noscript/template removal +
//! flattenHtmlLists nested→flat list rewrite) followed by TipTap's
//! `generateJSON(html, EXPORT_EXTENSIONS)`, i.e. ProseMirror's DOMParser over
//! the schema compiled from frontend/src/lib/tiptap-export-extensions.ts.
//!
//! The output is the RAW generateJSON-equivalent TipTap JSON; callers feed it
//! through `normalize_imported_tiptap_json` (content_parse.rs) exactly like
//! the TS does. Verified against fixtures generated by running the actual TS
//! path: frontend/scripts/generate-html-tiptap-fixtures.test.mts →
//! tests/fixtures/html_to_tiptap/ → tests/html_to_tiptap.rs.
//!
//! Faithfulness notes:
//! - HTML parsing uses html5ever (via `scraper`), the same spec algorithm
//!   browsers use; the TS path parses with jsdom (prepare pass) + happy-dom
//!   (generateJSON). Divergences are limited to non-spec-compliant happy-dom
//!   corners (e.g. `<image>` → `<img>` coercion).
//! - The ProseMirror DOMParser core (prosemirror-model 1.25.4 from_dom.ts:
//!   ParseContext / NodeContext, whitespace normalization, findPlace
//!   wrapping, blockTags sync, leaf fallbacks, Fragment text-node merging,
//!   required-content filling) is ported against a hardcoded mini-schema
//!   matching the compiled EXPORT_EXTENSIONS schema (node content
//!   expressions, attribute defaults, tag/style rule order, mark rank order).
//! - Unsupported-by-design (never produced by web content; documented gaps):
//!   footnote / wikilink / mathInline / mathBlock / commentMark parse rules
//!   (`<footnote>`, `span[data-footnote]`, `span[data-comment-id]`,
//!   `span[data-math-inline]`, `div[data-math-block]`) — these elements fall
//!   through to the unknown-element (transparent) path instead.
//! - `colspan`/`rowspan` are parsed as strings when present (TipTap's default
//!   attribute parse is `getAttribute`), defaulting to the number 1 —
//!   matching the TS byte-for-byte.

#![allow(dead_code)]

