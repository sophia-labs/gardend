#[derive(Debug, Clone, PartialEq)]
struct MarkInst {
    rank: u8,
    name: &'static str,
    attrs: Map<String, Value>,
}

impl MarkInst {
    fn simple(rank: u8, name: &'static str) -> Self {
        MarkInst {
            rank,
            name,
            attrs: Map::new(),
        }
    }

    fn to_json(&self) -> Value {
        if self.attrs.is_empty() {
            json!({"type": self.name})
        } else {
            json!({"type": self.name, "attrs": self.attrs})
        }
    }
}

// Mark rank order from the compiled schema:
// link, textStyle, bold, code, italic, strike, underline, highlight
const RANK_LINK: u8 = 0;
const RANK_TEXT_STYLE: u8 = 1;
const RANK_BOLD: u8 = 2;
const RANK_CODE: u8 = 3;
const RANK_ITALIC: u8 = 4;
const RANK_STRIKE: u8 = 5;
const RANK_UNDERLINE: u8 = 6;
const RANK_HIGHLIGHT: u8 = 7;

/// Mark.addToSet over a rank-sorted set: same-type marks are replaced.
fn add_to_set(set: &mut Vec<MarkInst>, mark: MarkInst) {
    if set
        .iter()
        .any(|existing| existing.name == mark.name && existing.attrs == mark.attrs)
    {
        return;
    }
    set.retain(|existing| existing.name != mark.name);
    let position = set
        .iter()
        .position(|existing| existing.rank > mark.rank)
        .unwrap_or(set.len());
    set.insert(position, mark);
}

fn marks_to_json(marks: &[MarkInst]) -> Value {
    Value::Array(marks.iter().map(MarkInst::to_json).collect())
}

// ─────────────────────────────────────────────────────────────────────────────
// Attribute computation (TipTap attribute parseHTML + defaults)
// ─────────────────────────────────────────────────────────────────────────────

const SOURCE_METADATA_ATTRIBUTES: &[&str] = &[
    "data-source-format",
    "data-source-approach",
    "data-source-page",
    "data-source-role",
    "data-source-id",
    "data-pdf-page",
    "data-pdf-role",
];

fn attr_or_null(el: Option<&DomElement>, name: &str) -> Value {
    el.and_then(|el| el.attr(name))
        .map(|value| json!(value))
        .unwrap_or(Value::Null)
}

fn source_metadata_attrs(map: &mut Map<String, Value>, el: Option<&DomElement>) {
    for name in SOURCE_METADATA_ATTRIBUTES {
        map.insert((*name).to_string(), attr_or_null(el, name));
    }
}

fn block_id_attr(map: &mut Map<String, Value>, el: Option<&DomElement>) {
    map.insert(
        "data-block-id".to_string(),
        attr_or_null(el, "data-block-id"),
    );
}

/// TextAlign parseHTML: element.style.textAlign if in the allowed alignments.
fn text_align_attr(map: &mut Map<String, Value>, el: Option<&DomElement>) {
    let alignment = el
        .and_then(|el| el.style_prop("text-align"))
        .filter(|value| {
            ["left", "center", "right", "justify"].contains(&value.to_lowercase().as_str())
        })
        .map(|value| json!(value.to_lowercase()))
        .unwrap_or(Value::Null);
    map.insert("textAlign".to_string(), alignment);
}

/// Outliner / ListItem indent: parseInt(data-indent, 10) else 0.
fn indent_attr(map: &mut Map<String, Value>, el: Option<&DomElement>) {
    let indent = el
        .and_then(|el| el.attr("data-indent"))
        .filter(|value| !value.is_empty())
        .and_then(parse_int_prefix)
        .unwrap_or(0);
    map.insert("indent".to_string(), json!(indent));
}

fn collapsed_attr(map: &mut Map<String, Value>, el: Option<&DomElement>) {
    let collapsed = el
        .and_then(|el| el.attr("data-collapsed"))
        .map(|value| value == "true")
        .unwrap_or(false);
    map.insert("collapsed".to_string(), json!(collapsed));
}

/// JS parseInt(value, 10): optional sign + leading digits.
fn parse_int_prefix(value: &str) -> Option<i64> {
    let trimmed = value.trim_start();
    let (sign, digits) = match trimmed.strip_prefix('-') {
        Some(rest) => (-1i64, rest),
        None => (1i64, trimmed.strip_prefix('+').unwrap_or(trimmed)),
    };
    let end = digits
        .char_indices()
        .take_while(|(_, c)| c.is_ascii_digit())
        .map(|(i, c)| i + c.len_utf8())
        .last()?;
    digits[..end].parse::<i64>().ok().map(|n| n * sign)
}

/// Attrs for a node created by a tag rule (`el` present) or synthesized as a
/// wrapper/filler (`el` absent → pure defaults). `heading_level` carries the
/// static rule attr for h1..h3.
fn node_attrs(
    nt: Nt,
    el: Option<&DomElement>,
    parent: Option<&DomElement>,
    heading_level: Option<i64>,
) -> Map<String, Value> {
    let mut map = Map::new();
    match nt {
        Nt::Paragraph | Nt::Heading => {
            block_id_attr(&mut map, el);
            source_metadata_attrs(&mut map, el);
            text_align_attr(&mut map, el);
            indent_attr(&mut map, el);
            collapsed_attr(&mut map, el);
            if nt == Nt::Heading {
                map.insert("level".to_string(), json!(heading_level.unwrap_or(1)));
            }
        }
        Nt::Blockquote => {
            block_id_attr(&mut map, el);
            source_metadata_attrs(&mut map, el);
            indent_attr(&mut map, el);
            collapsed_attr(&mut map, el);
        }
        Nt::HorizontalRule => {
            block_id_attr(&mut map, el);
            source_metadata_attrs(&mut map, el);
        }
        Nt::CodeBlock => {
            block_id_attr(&mut map, el);
            source_metadata_attrs(&mut map, el);
            // CodeBlock language: language-<x> class on the first element
            // child (the <code>).
            let language = el
                .and_then(|el| el.first_element_child())
                .and_then(|code| code.attr("class"))
                .and_then(|classes| {
                    classes
                        .split_ascii_whitespace()
                        .find_map(|class| class.strip_prefix("language-"))
                        .map(|language| language.to_string())
                })
                .filter(|language| !language.is_empty())
                .map(|language| json!(language))
                .unwrap_or(Value::Null);
            map.insert("language".to_string(), language);
        }
        Nt::ListItem => {
            block_id_attr(&mut map, el);
            source_metadata_attrs(&mut map, el);
            indent_attr(&mut map, el);
            collapsed_attr(&mut map, el);
            // ListItem listType: data-list-type, else inferred from parent.
            let list_type = el
                .and_then(|el| el.attr("data-list-type"))
                .filter(|value| !value.is_empty())
                .map(|value| value.to_string())
                .or_else(|| {
                    let parent = parent?;
                    if parent.tag == "ol" {
                        Some("ordered".to_string())
                    } else if parent.attr("data-type") == Some("taskList") {
                        Some("task".to_string())
                    } else {
                        Some("bullet".to_string())
                    }
                })
                .unwrap_or_else(|| "bullet".to_string());
            map.insert("listType".to_string(), json!(list_type));
            let checked = el
                .and_then(|el| el.attr("data-checked"))
                .map(|value| value == "true")
                .unwrap_or(false);
            map.insert("checked".to_string(), json!(checked));
        }
        Nt::Image => {
            block_id_attr(&mut map, el);
            source_metadata_attrs(&mut map, el);
            // ImageBlock parseHTML: prefer the <img> child when the matched
            // element is a wrapper (div.image-block).
            let img = el.and_then(|el| {
                if el.tag == "img" {
                    Some(el)
                } else {
                    el.first_descendant_img()
                }
            });
            let pick = |name: &str| -> Option<String> {
                img.and_then(|img| img.attr(name))
                    .filter(|value| !value.is_empty())
                    .or_else(|| el.and_then(|el| el.attr(name)).filter(|v| !v.is_empty()))
                    .map(|value| value.to_string())
            };
            map.insert(
                "src".to_string(),
                pick("src").map(|v| json!(v)).unwrap_or(Value::Null),
            );
            map.insert("alt".to_string(), json!(pick("alt").unwrap_or_default()));
            map.insert(
                "title".to_string(),
                pick("title").map(|v| json!(v)).unwrap_or(Value::Null),
            );
            let size = el
                .and_then(|el| el.attr("data-size"))
                .filter(|value| !value.is_empty())
                .unwrap_or("large");
            map.insert("size".to_string(), json!(size));
        }
        Nt::Table => {
            source_metadata_attrs(&mut map, el);
            indent_attr(&mut map, el);
            collapsed_attr(&mut map, el);
        }
        Nt::TableRow => {
            source_metadata_attrs(&mut map, el);
        }
        Nt::TableHeader | Nt::TableCell => {
            source_metadata_attrs(&mut map, el);
            // TipTap default attribute parse: getAttribute → string when
            // present; numeric default 1 otherwise.
            for name in ["colspan", "rowspan"] {
                let value = el
                    .and_then(|el| el.attr(name))
                    .map(|value| json!(value))
                    .unwrap_or(json!(1));
                map.insert(name.to_string(), value);
            }
            let colwidth = el
                .and_then(|el| el.attr("colwidth"))
                .filter(|value| !value.is_empty())
                .map(|value| {
                    Value::Array(
                        value
                            .split(',')
                            .map(|part| {
                                parse_int_prefix(part)
                                    .map(|n| json!(n))
                                    .unwrap_or(Value::Null)
                            })
                            .collect(),
                    )
                })
                .unwrap_or(Value::Null);
            map.insert("colwidth".to_string(), colwidth);
        }
        Nt::Doc | Nt::HardBreak | Nt::Text => {}
    }
    map
}

