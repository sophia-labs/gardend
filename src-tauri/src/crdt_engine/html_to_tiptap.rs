#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
enum Nt {
    Doc,
    Paragraph,
    Heading,
    Blockquote,
    CodeBlock,
    HorizontalRule,
    Image,
    ListItem,
    Table,
    TableRow,
    TableHeader,
    TableCell,
    HardBreak,
    Text,
}

impl Nt {
    fn name(self) -> &'static str {
        match self {
            Nt::Doc => "doc",
            Nt::Paragraph => "paragraph",
            Nt::Heading => "heading",
            Nt::Blockquote => "blockquote",
            Nt::CodeBlock => "codeBlock",
            Nt::HorizontalRule => "horizontalRule",
            Nt::Image => "image",
            Nt::ListItem => "listItem",
            Nt::Table => "table",
            Nt::TableRow => "tableRow",
            Nt::TableHeader => "tableHeader",
            Nt::TableCell => "tableCell",
            Nt::HardBreak => "hardBreak",
            Nt::Text => "text",
        }
    }

    fn is_inline(self) -> bool {
        matches!(self, Nt::Text | Nt::HardBreak)
    }

    fn is_leaf(self) -> bool {
        matches!(
            self,
            Nt::Text | Nt::HardBreak | Nt::HorizontalRule | Nt::Image
        )
    }

    fn inline_content(self) -> bool {
        matches!(self, Nt::Paragraph | Nt::Heading | Nt::CodeBlock)
    }

    /// Whether marks survive on children inserted directly into this node
    /// (NodeType.allowsMarkType): inline-content nodes allow all marks except
    /// codeBlock (`marks: ""`); block-content nodes allow none.
    fn allows_marks(self) -> bool {
        matches!(self, Nt::Paragraph | Nt::Heading)
    }

    /// Allowed direct children, in compiled-schema match order (drives
    /// findWrapping BFS order).
    fn allowed_children(self) -> &'static [Nt] {
        const BLOCKS: &[Nt] = &[
            Nt::Paragraph,
            Nt::Blockquote,
            Nt::Heading,
            Nt::HorizontalRule,
            Nt::CodeBlock,
            Nt::Table,
            Nt::ListItem,
            Nt::Image,
        ];
        const INLINE: &[Nt] = &[Nt::Text, Nt::HardBreak];
        match self {
            Nt::Doc | Nt::Blockquote | Nt::TableHeader | Nt::TableCell => BLOCKS,
            Nt::Paragraph | Nt::Heading => INLINE,
            Nt::CodeBlock => &[Nt::Text],
            Nt::ListItem => &[Nt::Paragraph, Nt::Heading, Nt::CodeBlock, Nt::Blockquote],
            Nt::Table => &[Nt::TableRow],
            Nt::TableRow => &[Nt::TableCell, Nt::TableHeader],
            _ => &[],
        }
    }

    /// Content expressions ending in `+` (must hold at least one child).
    fn requires_content(self) -> bool {
        matches!(
            self,
            Nt::Doc | Nt::Blockquote | Nt::ListItem | Nt::Table | Nt::TableHeader | Nt::TableCell
        )
    }

    fn fits(self, child: Nt) -> bool {
        self.allowed_children().contains(&child)
    }
}

/// ContentMatch.findWrapping: shortest chain of wrapper node types so that
/// `target` fits inside `parent`. Empty vec = fits directly.
fn find_wrapping(parent: Nt, target: Nt) -> Option<Vec<Nt>> {
    if parent.fits(target) {
        return Some(Vec::new());
    }
    let mut seen: HashSet<Nt> = HashSet::new();
    let mut queue: std::collections::VecDeque<(Nt, Vec<Nt>)> = Default::default();
    for &child in parent.allowed_children() {
        if !child.is_leaf() && seen.insert(child) {
            queue.push_back((child, vec![child]));
        }
    }
    while let Some((node_type, route)) = queue.pop_front() {
        if node_type.fits(target) {
            return Some(route);
        }
        for &child in node_type.allowed_children() {
            if !child.is_leaf() && seen.insert(child) {
                let mut next = route.clone();
                next.push(child);
                queue.push_back((child, next));
            }
        }
    }
    None
}

