// ─────────────────────────────────────────────────────────────────────────────
// Simple owned DOM (built from scraper/html5ever, mutable for list flattening)
// ─────────────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone)]
pub(crate) enum DomNode {
    Element(DomElement),
    Text(String),
}

#[derive(Debug, Clone)]
pub(crate) struct DomElement {
    pub(crate) tag: String,
    pub(crate) attrs: Vec<(String, String)>,
    pub(crate) children: Vec<DomNode>,
}

impl DomElement {
    pub(crate) fn attr(&self, name: &str) -> Option<&str> {
        self.attrs
            .iter()
            .find(|(key, _)| key == name)
            .map(|(_, value)| value.as_str())
    }

    fn set_attr(&mut self, name: &str, value: String) {
        if let Some(entry) = self.attrs.iter_mut().find(|(key, _)| key == name) {
            entry.1 = value;
        } else {
            self.attrs.push((name.to_string(), value));
        }
    }

    fn has_class(&self, class: &str) -> bool {
        self.attr("class")
            .map(|value| value.split_ascii_whitespace().any(|c| c == class))
            .unwrap_or(false)
    }

    /// Inline-style property lookup (lowercased property names).
    fn style_prop(&self, prop: &str) -> Option<String> {
        let style = self.attr("style")?;
        for decl in style.split(';') {
            let mut parts = decl.splitn(2, ':');
            let name = parts.next()?.trim().to_lowercase();
            if name == prop {
                return Some(parts.next().unwrap_or("").trim().to_string());
            }
        }
        None
    }

    fn first_element_child(&self) -> Option<&DomElement> {
        self.children.iter().find_map(|child| match child {
            DomNode::Element(el) => Some(el),
            _ => None,
        })
    }

    fn first_descendant_img(&self) -> Option<&DomElement> {
        for child in &self.children {
            if let DomNode::Element(el) = child {
                if el.tag == "img" {
                    return Some(el);
                }
                if let Some(found) = el.first_descendant_img() {
                    return Some(found);
                }
            }
        }
        None
    }
}

/// Tags removed up-front by prepareHtmlForTipTapImport.
const PREPARE_REMOVE_TAGS: &[&str] = &["script", "style", "noscript", "template"];

/// Parse `html` and return the `<body>` element as an owned tree, with the
/// prepare-pass removals applied.
pub(crate) fn build_body_dom(html: &str) -> DomElement {
    let parsed = scraper::Html::parse_document(html);
    let selector = scraper::Selector::parse("body").expect("valid selector");
    match parsed.select(&selector).next() {
        Some(body) => convert_element(body),
        None => DomElement {
            tag: "body".into(),
            attrs: Vec::new(),
            children: Vec::new(),
        },
    }
}

pub(crate) fn convert_element(el: scraper::ElementRef) -> DomElement {
    let tag = el.value().name().to_lowercase();
    let attrs: Vec<(String, String)> = el
        .value()
        .attrs()
        .map(|(name, value)| (name.to_lowercase(), value.to_string()))
        .collect();
    let mut children: Vec<DomNode> = Vec::new();
    for child in el.children() {
        match child.value() {
            scraper::Node::Text(text) => {
                // DOM semantics: contiguous text is one text node.
                if let Some(DomNode::Text(last)) = children.last_mut() {
                    last.push_str(text);
                } else {
                    children.push(DomNode::Text(text.to_string()));
                }
            }
            scraper::Node::Element(element) => {
                let child_tag = element.name().to_lowercase();
                if PREPARE_REMOVE_TAGS.contains(&child_tag.as_str()) {
                    continue;
                }
                if let Some(child_ref) = scraper::ElementRef::wrap(child) {
                    children.push(DomNode::Element(convert_element(child_ref)));
                }
            }
            _ => {}
        }
    }
    DomElement {
        tag,
        attrs,
        children,
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// flattenHtmlLists (artifact-ingest.ts): nested <ul>/<ol> → flat li sequence
// with data-list-type / data-indent / data-checked.
// ─────────────────────────────────────────────────────────────────────────────

pub(crate) fn flatten_html_lists(root: &mut DomElement) {
    flatten_walk(root, false);
}

fn flatten_walk(el: &mut DomElement, inside_li: bool) {
    for child in el.children.iter_mut() {
        let DomNode::Element(child_el) = child else {
            continue;
        };
        let is_list = child_el.tag == "ul" || child_el.tag == "ol";
        if is_list && !inside_li {
            let mut flat = DomElement {
                tag: child_el.tag.clone(),
                attrs: Vec::new(),
                children: Vec::new(),
            };
            append_flattened_list_items(child_el, &mut flat, 0);
            *child_el = flat;
            // The replacement flat list is not re-processed (TS snapshot
            // semantics: querySelectorAll ran before any replaceWith).
            continue;
        }
        let next_inside_li = inside_li || child_el.tag == "li";
        flatten_walk(child_el, next_inside_li);
    }
}

fn append_flattened_list_items(list: &DomElement, target: &mut DomElement, indent: usize) {
    let default_type = if list.tag == "ol" {
        "ordered"
    } else {
        "bullet"
    };
    for item in &list.children {
        let DomNode::Element(item_el) = item else {
            continue;
        };
        if item_el.tag != "li" {
            continue;
        }
        let mut clone = item_el.clone();
        clone.children.retain(
            |child| !matches!(child, DomNode::Element(el) if el.tag == "ul" || el.tag == "ol"),
        );
        let checkbox_checked = remove_first_own_checkbox(&mut clone);
        let list_type = if checkbox_checked.is_some() {
            "task"
        } else {
            default_type
        };
        clone.set_attr("data-list-type", list_type.to_string());
        clone.set_attr("data-indent", indent.to_string());
        if let Some(checked) = checkbox_checked {
            clone.set_attr(
                "data-checked",
                if checked { "true" } else { "false" }.to_string(),
            );
        }
        target.children.push(DomNode::Element(clone));
        for nested in &item_el.children {
            if let DomNode::Element(el) = nested {
                if el.tag == "ul" || el.tag == "ol" {
                    append_flattened_list_items(el, target, indent + 1);
                }
            }
        }
    }
}

/// Port of firstOwnCheckbox + removal: the first `input[type=checkbox]`
/// descendant whose nearest `li` ancestor is the item itself. Returns its
/// checked state after removing it.
fn remove_first_own_checkbox(item: &mut DomElement) -> Option<bool> {
    fn walk(el: &mut DomElement) -> Option<bool> {
        let mut found: Option<(usize, bool)> = None;
        for (index, child) in el.children.iter().enumerate() {
            if let DomNode::Element(child_el) = child {
                if child_el.tag == "input"
                    && child_el
                        .attr("type")
                        .map(|t| t.eq_ignore_ascii_case("checkbox"))
                        .unwrap_or(false)
                {
                    found = Some((index, child_el.attr("checked").is_some()));
                    break;
                }
            }
        }
        if let Some((index, checked)) = found {
            el.children.remove(index);
            return Some(checked);
        }
        for child in el.children.iter_mut() {
            if let DomNode::Element(child_el) = child {
                if child_el.tag == "li" {
                    continue; // belongs to a nested item
                }
                if let Some(checked) = walk(child_el) {
                    return Some(checked);
                }
            }
        }
        None
    }
    walk(item)
}

/// prosemirror-model normalizeList: move list elements that directly follow a
/// `li` sibling into that `li` (invalid-HTML fixup). Applied to every list.
fn normalize_lists_recursive(el: &mut DomElement) {
    if el.tag == "ul" || el.tag == "ol" {
        let mut index = 0usize;
        let mut prev_item: Option<usize> = None;
        while index < el.children.len() {
            let tag = match &el.children[index] {
                DomNode::Element(child) => Some(child.tag.clone()),
                _ => None,
            };
            match tag.as_deref() {
                Some("ul") | Some("ol") if prev_item.is_some() => {
                    let moved = el.children.remove(index);
                    if let Some(prev) = prev_item {
                        if let DomNode::Element(prev_el) = &mut el.children[prev] {
                            prev_el.children.push(moved);
                        }
                    }
                    // resume at the element that shifted into `index`
                }
                Some("li") => {
                    prev_item = Some(index);
                    index += 1;
                }
                Some(_) => {
                    prev_item = None;
                    index += 1;
                }
                None => {
                    index += 1;
                }
            }
        }
    }
    for child in el.children.iter_mut() {
        if let DomNode::Element(child_el) = child {
            normalize_lists_recursive(child_el);
        }
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Mini schema (compiled EXPORT_EXTENSIONS schema, from the fixture dump)
