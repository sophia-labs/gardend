enum RuleOut {
    Node {
        nt: Nt,
        attrs: Map<String, Value>,
        preserve_full: bool,
    },
    Mark(MarkInst),
    NoRule,
    Ignore,
}

static ALLOWED_URI_RE: LazyLock<regex::Regex> = LazyLock::new(|| {
    regex::Regex::new(
        r"(?i)^(?:(?:http|https|ftp|ftps|mailto|tel|callto|sms|cid|xmpp):|[^a-zA-Z]|[a-zA-Z0-9+.\-]+(?:[^a-zA-Z+.\-:]|$))",
    )
    .expect("valid regex")
});

/// Port of @tiptap/extension-link isAllowedUri (whitespace stripped first).
fn is_allowed_uri(uri: &str) -> bool {
    let stripped: String = uri.chars().filter(|c| !is_js_whitespace(*c)).collect();
    stripped.is_empty() || ALLOWED_URI_RE.is_match(&stripped)
}

pub(crate) fn is_js_whitespace(c: char) -> bool {
    matches!(
        c,
        '\t' | '\n' | '\u{b}' | '\u{c}' | '\r' | ' ' | '\u{a0}' | '\u{1680}' | '\u{2000}'
            ..='\u{200a}'
                | '\u{2028}'
                | '\u{2029}'
                | '\u{202f}'
                | '\u{205f}'
                | '\u{3000}'
                | '\u{feff}'
    )
}

