const OPT_PRESERVE_WS: u8 = 1;
const OPT_PRESERVE_WS_FULL: u8 = 2;

fn ws_options_for(nt: Nt, preserve_full: Option<bool>, base: u8) -> u8 {
    match preserve_full {
        Some(true) => OPT_PRESERVE_WS | OPT_PRESERVE_WS_FULL,
        Some(false) => OPT_PRESERVE_WS,
        None => {
            if nt == Nt::CodeBlock {
                // whitespace: "pre" (code: true)
                OPT_PRESERVE_WS | OPT_PRESERVE_WS_FULL
            } else {
                base
            }
        }
    }
}

struct NodeCtx {
    id: u64,
    nt: Nt,
    attrs: Map<String, Value>,
    content: Vec<Value>,
    solid: bool,
    options: u8,
}

impl NodeCtx {
    /// NodeContext.finish(openEnd=false): trailing-whitespace strip, adjacent
    /// text merge (Fragment.fromArray) and required-content fill.
    fn finish(mut self) -> Value {
        if self.options & OPT_PRESERVE_WS == 0 {
            if let Some(last) = self.content.last_mut() {
                if last.get("type").and_then(Value::as_str) == Some("text") {
                    let text = last
                        .get("text")
                        .and_then(Value::as_str)
                        .unwrap_or_default()
                        .to_string();
                    let stripped = text.trim_end_matches([' ', '\t', '\r', '\n', '\u{c}']);
                    if stripped.is_empty() {
                        self.content.pop();
                    } else if stripped.len() != text.len() {
                        last["text"] = json!(stripped);
                    }
                }
            }
        }
        let mut merged: Vec<Value> = Vec::new();
        for node in self.content {
            let is_text = node.get("type").and_then(Value::as_str) == Some("text");
            if is_text {
                if let Some(prev) = merged.last_mut() {
                    let prev_is_text = prev.get("type").and_then(Value::as_str) == Some("text");
                    if prev_is_text && prev.get("marks") == node.get("marks") {
                        let combined = format!(
                            "{}{}",
                            prev.get("text").and_then(Value::as_str).unwrap_or(""),
                            node.get("text").and_then(Value::as_str).unwrap_or("")
                        );
                        prev["text"] = json!(combined);
                        continue;
                    }
                }
            }
            merged.push(node);
        }
        if merged.is_empty() && self.nt.requires_content() {
            merged.push(default_fill(self.nt));
        }
        let mut out = Map::new();
        out.insert("type".to_string(), json!(self.nt.name()));
        if !self.attrs.is_empty() {
            out.insert("attrs".to_string(), Value::Object(self.attrs));
        }
        if !merged.is_empty() {
            out.insert("content".to_string(), json!(merged));
        }
        Value::Object(out)
    }
}

/// ContentMatch.fillBefore: the default node created to satisfy a `+`
/// expression (first allowed child type, recursively filled).
fn default_fill(parent: Nt) -> Value {
    let child = parent.allowed_children()[0];
    let mut out = Map::new();
    out.insert("type".to_string(), json!(child.name()));
    let attrs = node_attrs(child, None, None, None);
    if !attrs.is_empty() {
        out.insert("attrs".to_string(), Value::Object(attrs));
    }
    if child.requires_content() {
        out.insert("content".to_string(), json!([default_fill(child)]));
    }
    Value::Object(out)
}

struct Parser {
    nodes: Vec<NodeCtx>,
    open: usize,
    local_preserve_ws: bool,
    next_id: u64,
}

impl Parser {
    fn new() -> Self {
        Parser {
            nodes: vec![NodeCtx {
                id: 0,
                nt: Nt::Doc,
                attrs: Map::new(),
                content: Vec::new(),
                solid: true,
                options: 0,
            }],
            open: 0,
            local_preserve_ws: false,
            next_id: 1,
        }
    }

    fn top(&self) -> &NodeCtx {
        &self.nodes[self.open]
    }

    fn top_mut(&mut self) -> &mut NodeCtx {
        &mut self.nodes[self.open]
    }

    fn add_all(&mut self, el: &DomElement, marks: &[MarkInst]) {
        // domNodeBefore: whether the previous DOM sibling is a <br> element.
        let mut prev_is_br = false;
        for child in &el.children {
            match child {
                DomNode::Text(text) => {
                    self.add_text_node(text, prev_is_br, marks);
                    prev_is_br = false;
                }
                DomNode::Element(child_el) => {
                    self.add_element(child_el, marks, Some(el));
                    prev_is_br = child_el.tag == "br";
                }
            }
        }
    }

    // Port of addTextNode. `prev_is_br`: the previous DOM sibling is a <br>.
    fn add_text_node(&mut self, value: &str, prev_is_br: bool, marks: &[MarkInst]) {
        let top = self.top();
        let preserve_full = top.options & OPT_PRESERVE_WS_FULL != 0;
        let preserve = self.local_preserve_ws || top.options & OPT_PRESERVE_WS != 0;
        let has_non_ws = value
            .chars()
            .any(|c| !matches!(c, ' ' | '\t' | '\r' | '\n' | '\u{c}'));
        let inline_context = top.nt.inline_content();
        if !(preserve_full || inline_context || has_non_ws) {
            return;
        }
        let mut text = value.to_string();
        if !preserve {
            text = collapse_html_ws(&text);
            if text.starts_with(' ') && self.open == self.nodes.len() - 1 {
                let node_before = self.top().content.last();
                let before_is_ws_text = node_before
                    .map(|node| {
                        node.get("type").and_then(Value::as_str) == Some("text")
                            && node
                                .get("text")
                                .and_then(Value::as_str)
                                .map(|t| t.ends_with([' ', '\t', '\r', '\n', '\u{c}']))
                                .unwrap_or(false)
                    })
                    .unwrap_or(false);
                if node_before.is_none() || prev_is_br || before_is_ws_text {
                    text.remove(0);
                }
            }
        } else if preserve_full {
            text = text.replace("\r\n", "\n").replace('\r', "\n");
        } else if text.contains(['\r', '\n'])
            && find_wrapping(self.top().nt, Nt::HardBreak).is_some()
        {
            // linebreakReplacement (hardBreak) path for preserve-ws contexts.
            let lines: Vec<String> = text
                .replace("\r\n", "\n")
                .replace('\r', "\n")
                .split('\n')
                .map(|line| line.to_string())
                .collect();
            for (index, line) in lines.iter().enumerate() {
                if index > 0 {
                    self.insert_leaf(Nt::HardBreak, Map::new(), marks, true);
                }
                if !line.is_empty() {
                    let all_ws = !line.chars().any(|c| !is_js_whitespace(c));
                    self.insert_text(line.clone(), marks, all_ws);
                }
            }
            return;
        } else {
            text = text.replace("\r\n", " ").replace(['\r', '\n'], " ");
        }
        if !text.is_empty() {
            let all_ws = !text.chars().any(|c| !is_js_whitespace(c));
            self.insert_text(text, marks, all_ws);
        }
    }

    fn add_element(&mut self, el: &DomElement, marks: &[MarkInst], parent: Option<&DomElement>) {
        let outer_ws = self.local_preserve_ws;
        if el.tag == "pre"
            || el
                .style_prop("white-space")
                .map(|value| value.contains("pre"))
                .unwrap_or(false)
        {
            self.local_preserve_ws = true;
        }
        match match_tag(el, parent) {
            RuleOut::Ignore => {}
            RuleOut::NoRule => {
                let mut sync_id: Option<u64> = None;
                let block_tag = BLOCK_TAGS.contains(&el.tag.as_str());
                if block_tag {
                    let first_is_inline = self
                        .top()
                        .content
                        .first()
                        .map(is_inline_json)
                        .unwrap_or(false);
                    if !self.top().content.is_empty() && first_is_inline && self.open > 0 {
                        self.open -= 1;
                    }
                    sync_id = Some(self.top().id);
                } else if el.children.is_empty() {
                    self.leaf_fallback(el, marks);
                    self.local_preserve_ws = outer_ws;
                    return;
                }
                let inner = read_styles(el, marks);
                self.add_all(el, &inner);
                if let Some(id) = sync_id {
                    self.sync_to_id(id);
                }
            }
            RuleOut::Mark(mark) => {
                let mut inner = read_styles(el, marks);
                inner.push(mark);
                self.add_all(el, &inner);
            }
            RuleOut::Node {
                nt,
                attrs,
                preserve_full,
            } => {
                let inner = read_styles(el, marks);
                if nt.is_leaf() {
                    if !self.insert_leaf(nt, attrs, &inner, el.tag == "br") {
                        self.leaf_fallback(el, &inner);
                    }
                } else {
                    let preserve = if preserve_full { Some(true) } else { None };
                    let entered = self.enter(nt, attrs, preserve);
                    let start_id = self.top().id;
                    self.add_all(el, &inner);
                    if entered && self.sync_to_id(start_id) {
                        self.open = self.open.saturating_sub(1);
                    }
                }
            }
        }
        self.local_preserve_ws = outer_ws;
    }

    // leafFallback: a <br> that could not be inserted becomes "\n" when the
    // top node has inline content (e.g. inside codeBlock).
    fn leaf_fallback(&mut self, el: &DomElement, marks: &[MarkInst]) {
        if el.tag == "br" && self.top().nt.inline_content() {
            self.add_text_node("\n", false, marks);
        }
    }

    fn insert_text(&mut self, text: String, marks: &[MarkInst], cautious: bool) -> bool {
        let node = json!({"type": "text", "text": text});
        self.insert_node(node, Nt::Text, marks, cautious)
    }

    fn insert_leaf(
        &mut self,
        nt: Nt,
        attrs: Map<String, Value>,
        marks: &[MarkInst],
        cautious: bool,
    ) -> bool {
        let mut node = Map::new();
        node.insert("type".to_string(), json!(nt.name()));
        if !attrs.is_empty() {
            node.insert("attrs".to_string(), Value::Object(attrs));
        }
        self.insert_node(Value::Object(node), nt, marks, cautious)
    }

    // Port of insertNode + findPlace.
    fn insert_node(&mut self, mut node: Value, nt: Nt, marks: &[MarkInst], cautious: bool) -> bool {
        if !self.find_place(nt, cautious) {
            return false;
        }
        self.close_extra();
        let top_allows_marks = self.top().nt.allows_marks();
        if top_allows_marks && !marks.is_empty() {
            let mut set: Vec<MarkInst> = Vec::new();
            for mark in marks {
                add_to_set(&mut set, mark.clone());
            }
            if !set.is_empty() {
                node["marks"] = marks_to_json(&set);
            }
        }
        self.top_mut().content.push(node);
        true
    }

    // findPlace: search depths open..0 for the shortest wrapping (with the
    // solid-node penalty), sync there, and enter the wrappers.
    fn find_place(&mut self, nt: Nt, cautious: bool) -> bool {
        let mut route: Option<Vec<Nt>> = None;
        let mut sync_idx: Option<usize> = None;
        let mut penalty = 0usize;
        for depth in (0..=self.open).rev() {
            let cx = &self.nodes[depth];
            if let Some(found) = find_wrapping(cx.nt, nt) {
                let better = match &route {
                    None => true,
                    Some(existing) => existing.len() > found.len() + penalty,
                };
                if better {
                    let empty = found.is_empty();
                    route = Some(found);
                    sync_idx = Some(depth);
                    if empty {
                        break;
                    }
                }
            }
            if cx.solid {
                if cautious {
                    break;
                }
                penalty += 2;
            }
        }
        let Some(route) = route else {
            return false;
        };
        if let Some(idx) = sync_idx {
            self.sync_to_id(self.nodes[idx].id);
        }
        for wrapper in route {
            self.enter_inner(wrapper, node_attrs(wrapper, None, None, None), false, None);
        }
        true
    }

    fn enter(&mut self, nt: Nt, attrs: Map<String, Value>, preserve: Option<bool>) -> bool {
        if !self.find_place(nt, false) {
            return false;
        }
        self.enter_inner(nt, attrs, true, preserve);
        true
    }

    fn enter_inner(
        &mut self,
        nt: Nt,
        attrs: Map<String, Value>,
        solid: bool,
        preserve: Option<bool>,
    ) {
        self.close_extra();
        let options = ws_options_for(nt, preserve, self.top().options);
        let id = self.next_id;
        self.next_id += 1;
        self.nodes.push(NodeCtx {
            id,
            nt,
            attrs,
            content: Vec::new(),
            solid,
            options,
        });
        self.open += 1;
    }

    fn close_extra(&mut self) {
        while self.nodes.len() - 1 > self.open {
            let ctx = self.nodes.pop().expect("non-empty stack");
            let finished = ctx.finish();
            self.nodes
                .last_mut()
                .expect("parent exists")
                .content
                .push(finished);
        }
    }

    // Port of sync(to): find the context by identity; set open. While
    // localPreserveWS is set, contexts scanned over get the WS bit.
    fn sync_to_id(&mut self, id: u64) -> bool {
        for index in (0..=self.open).rev() {
            if self.nodes[index].id == id {
                self.open = index;
                return true;
            }
            if self.local_preserve_ws {
                self.nodes[index].options |= OPT_PRESERVE_WS;
            }
        }
        false
    }

    fn finish(mut self) -> Value {
        self.open = 0;
        self.close_extra();
        self.nodes.pop().expect("doc context").finish()
    }
}

fn is_inline_json(node: &Value) -> bool {
    matches!(
        node.get("type").and_then(Value::as_str),
        Some("text") | Some("hardBreak")
    )
}

/// HTML whitespace collapse: runs of [ \t\r\n\f] → single space.
fn collapse_html_ws(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    let mut in_ws = false;
    for c in value.chars() {
        if matches!(c, ' ' | '\t' | '\r' | '\n' | '\u{c}') {
            if !in_ws {
                out.push(' ');
                in_ws = true;
            }
        } else {
            out.push(c);
            in_ws = false;
        }
    }
    out
}

